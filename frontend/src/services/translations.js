export const translateTextItem = (text, lang = 'mr') => {
  if (!text) return text;
  // If user is in English mode, clean up bilingual titles like "मासिक बचत सभा (Monthly Bachat Meeting)"
  if (lang === 'en') {
    if (text.includes('(') && text.includes(')')) {
      const match = text.match(/\((.*?)\)/);
      if (match && match[1]) return match[1];
    }
  }
  return text;
};
